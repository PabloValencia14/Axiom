    fun searchCurated(query: String): List<CatalogBook> {
        val q = query.lowercase().trim()
        if (q.isBlank()) return ALL_CURATED

        val tokens = q.split(Regex("[^\\p{L}\\p{Nd}]+")).filter { it.length > 1 }

        return ALL_CURATED.filter { book ->
            val title = book.title.lowercase()
            val author = book.author.lowercase()

            if (title.contains(q) || author.contains(q)) return@filter true

            tokens.any { t ->
                title.contains(t) || author.contains(t) ||
                (t in listOf("bucear", "verano", "dyksommar") && (book == BUCEAR_EN_VERANO || book == BECKOMBERGA)) ||
                (t in listOf("stridsberg", "sara") && book.author.contains("Stridsberg", true))
            }
        }
    }
